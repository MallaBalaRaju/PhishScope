import { 
  ReceivedHop, 
  EvidenceFinding, 
  EmailEnvelope,
  IpType 
} from '../../src/types/forensics';
import { extractIps, classifyDetailedIp, IpClassificationDetails } from '../utils/ipUtils';

export interface CandidateSourceIpInfo {
  ip: string;
  confidence: string;
  justification: string;
  ipType: IpType;
  attributionCategory: 'confirmed_originating' | 'candidate_originating' | 'observed_relay';
  trustBoundary: 'border' | 'untrusted_external' | 'internal_submission';
  isSpecialPurpose: boolean;
  hopIndex?: number;
  rawPositionFromTop?: number;
}

export interface HeaderForensicResults {
  receivedHops: ReceivedHop[];
  candidateSourceIps: CandidateSourceIpInfo[];
  routingAnomalies: EvidenceFinding[];
  identityMismatches: EvidenceFinding[];
  messageIdAnomalies: EvidenceFinding[];
  dateAnomalies: EvidenceFinding[];
}

/**
 * Parses individual Received headers into structured hops.
 * Preserves original values, header indices, and calculates chronological relay progression.
 * Top Received header (index 0 in raw headers) is the recipient's border MTA (latest in time).
 * Bottom Received header is the earliest hop recorded.
 */
export function parseReceivedChain(receivedHeaders: string[]): ReceivedHop[] {
  const totalHops = receivedHeaders.length;
  if (totalHops === 0) return [];

  // In RFC 5321/5322, MTAs prepend headers:
  // rawHeaders[0] = Topmost hop (Border receiving MTA, latest in time)
  // rawHeaders[N-1] = Bottommost hop (Earliest hop in chain)
  // Chronological order: [0] = Earliest, [N-1] = Latest
  const chronological = [...receivedHeaders].reverse();
  const hops: ReceivedHop[] = [];

  let previousTimestamp: Date | null = null;

  for (let i = 0; i < chronological.length; i++) {
    const raw = chronological[i];
    const rawPositionFromTop = totalHops - 1 - i; // 0 for the topmost header in original message
    const isBorderHop = (rawPositionFromTop === 0);
    const suspiciousSignals: string[] = [];

    // Extract reporting server: from <server> (<rdns> [<ip>])
    const fromMatch = raw.match(/from\s+([^\s;]+)(?:\s+\(([^)]+)\))?/i);
    const reportingServer = fromMatch ? fromMatch[1].trim() : undefined;
    const parenthetical = fromMatch ? fromMatch[2] : '';

    // Extract receiving server: by <server>
    const byMatch = raw.match(/\bby\s+([^\s;]+)/i);
    const byServer = byMatch ? byMatch[1].trim() : undefined;

    // Extract protocol: with <protocol>
    const withMatch = raw.match(/\bwith\s+([^\s;]+)/i);
    const protocol = withMatch ? withMatch[1].trim() : undefined;

    // Extract timestamp after semicolon
    let timestamp: string | undefined = undefined;
    let hopDate: Date | null = null;
    let timeDeltaSeconds: number | undefined = undefined;

    const semiIdx = raw.lastIndexOf(';');
    if (semiIdx !== -1) {
      const datePart = raw.slice(semiIdx + 1).trim();
      const parsedDate = new Date(datePart);
      if (!isNaN(parsedDate.getTime())) {
        hopDate = parsedDate;
        timestamp = parsedDate.toISOString();
      } else {
        suspiciousSignals.push(`Unparseable timestamp in hop: "${datePart}"`);
      }
    }

    if (hopDate && previousTimestamp) {
      timeDeltaSeconds = Math.round((hopDate.getTime() - previousTimestamp.getTime()) / 1000);
      if (timeDeltaSeconds < -120) {
        suspiciousSignals.push(`Negative transit time (${timeDeltaSeconds}s): hop timestamp predates previous hop, indicating clock desynchronization or forged header insertion.`);
      } else if (timeDeltaSeconds > 86400 * 2) {
        suspiciousSignals.push(`Abnormally high transit delay (${Math.round(timeDeltaSeconds / 3600)}h) between mail hops.`);
      }
    }
    if (hopDate) {
      previousTimestamp = hopDate;
    }

    // Extract IP address from parenthetical or overall hop text
    const ips = extractIps(parenthetical || raw);
    let ipAddress: string | undefined = undefined;
    let ipType: IpType = 'invalid';

    if (ips.length > 0) {
      // Prioritize IP inside parenthetical after 'from'
      ipAddress = ips[0].ip;
      ipType = ips[0].type;
    }

    // Hostname
    let hostname: string | undefined = reportingServer;
    if (parenthetical) {
      const words = parenthetical.split(/\s+/);
      const possibleHost = words.find(w => w.includes('.') && !w.match(/^\d+\.\d+/));
      if (possibleHost) hostname = possibleHost.replace(/[\[\]]/g, '');
    }

    // Trust boundary assignment:
    // Topmost header (rawPositionFromTop === 0) is generated by the recipient's trusted border MTA.
    // It is within the trusted border.
    // Hops earlier than the border MTA are external and potentially untrusted.
    // If negative transit time or obvious forged syntax is observed, flag as potentially forged.
    let trustZone: 'trusted_border' | 'trusted_internal' | 'untrusted_external' | 'potentially_forged' = 'untrusted_external';
    let isPotentiallyForged = false;

    if (isBorderHop) {
      trustZone = 'trusted_border';
    } else if (suspiciousSignals.some(s => s.includes('Negative transit time') || s.includes('Unparseable timestamp'))) {
      trustZone = 'potentially_forged';
      isPotentiallyForged = true;
    } else {
      trustZone = 'untrusted_external';
    }

    // Heuristics on hop structure
    if (raw.toLowerCase().includes('localhost') && i > 0 && !isBorderHop) {
      suspiciousSignals.push('Internal localhost loopback referenced in intermediate external hop.');
    }

    hops.push({
      hopIndex: i + 1,
      rawPositionFromTop,
      reportingServer,
      receivingServer: byServer,
      byServer,
      ipAddress,
      ipType,
      hostname,
      timestamp,
      timeDeltaSeconds,
      protocol,
      rawHeader: raw,
      parsingConfidence: (reportingServer || byServer) ? (ipAddress ? 0.95 : 0.75) : 0.4,
      suspiciousSignals,
      trustZone,
      isBorderHop,
      isPotentiallyForged
    });
  }

  return hops;
}

/**
 * Determines candidate sending IP addresses from parsed hops with explicit trust boundary awareness.
 * Distinguishes:
 * - confirmed_originating: Authenticated client submission (e.g. ESMTPSA or authenticated user).
 * - candidate_originating: External public connecting MTA or earliest credible external hop.
 * - observed_relay: Intermediate mail transfer agent.
 * Never assumes the earliest public IP is the true sender if it comes from an untrusted or forged header!
 */
export function identifyCandidateSourceIps(hops: ReceivedHop[]): CandidateSourceIpInfo[] {
  const candidates: CandidateSourceIpInfo[] = [];
  const seenIps = new Set<string>();

  if (hops.length === 0) return [];

  // Identify the border receiving hop (rawPositionFromTop === 0)
  const borderHop = hops.find(h => h.isBorderHop);
  const borderConnectingIp = borderHop?.ipAddress;

  // Check each hop in chronological order
  for (const hop of hops) {
    if (!hop.ipAddress || seenIps.has(hop.ipAddress)) continue;
    seenIps.add(hop.ipAddress);

    const ipDetails = classifyDetailedIp(hop.ipAddress);
    const isSpecial = ipDetails.isSpecialPurpose;
    const isPublicCandidate = ipDetails.isPublicCandidate;

    // Check for authenticated client submission
    const isAuthSubmission = !!(hop.protocol && /esmtpsa|authenticated/i.test(hop.protocol)) ||
      /auth=|authenticated/i.test(hop.rawHeader);

    if (isAuthSubmission && isPublicCandidate) {
      candidates.push({
        ip: hop.ipAddress,
        confidence: 'High (Confirmed authenticated submission)',
        justification: `Hop #${hop.hopIndex} recorded authenticated client submission (${hop.protocol || 'ESMTPSA'}). Authenticated client IP directly established.`,
        ipType: hop.ipType,
        attributionCategory: 'confirmed_originating',
        trustBoundary: 'untrusted_external',
        isSpecialPurpose: false,
        hopIndex: hop.hopIndex,
        rawPositionFromTop: hop.rawPositionFromTop
      });
      continue;
    }

    if (hop.isBorderHop) {
      // The IP observed connecting to the recipient's border MTA is the most reliably witnessed public IP
      candidates.push({
        ip: hop.ipAddress,
        confidence: isPublicCandidate 
          ? 'High (Verified border connecting IP recorded by recipient MTA)' 
          : `Low (Border MTA connected from ${hop.ipType} address space)`,
        justification: `Directly logged by recipient border MTA (hop position #${hop.rawPositionFromTop} from top). This represents the verified network connection crossing the recipient trust boundary.`,
        ipType: hop.ipType,
        attributionCategory: isPublicCandidate ? 'candidate_originating' : 'observed_relay',
        trustBoundary: 'border',
        isSpecialPurpose: isSpecial,
        hopIndex: hop.hopIndex,
        rawPositionFromTop: hop.rawPositionFromTop
      });
      continue;
    }

    // For hops earlier than the border MTA:
    if (hop.isPotentiallyForged) {
      candidates.push({
        ip: hop.ipAddress,
        confidence: 'Low (Potentially forged or untrusted hop)',
        justification: `Recorded in hop #${hop.hopIndex} which exhibited routing anomalies or invalid timing. Cannot be verified as an authentic originating IP without corroborating authentication records.`,
        ipType: hop.ipType,
        attributionCategory: 'observed_relay',
        trustBoundary: 'untrusted_external',
        isSpecialPurpose: isSpecial,
        hopIndex: hop.hopIndex,
        rawPositionFromTop: hop.rawPositionFromTop
      });
    } else if (isPublicCandidate) {
      // Earliest public IP in unverified chain
      const isEarliestHop = (hop.hopIndex === 1);
      candidates.push({
        ip: hop.ipAddress,
        confidence: isEarliestHop 
          ? 'Medium (Candidate origin from earliest unconfirmed hop; subject to header injection if border relay did not authenticate)' 
          : 'Medium (Intermediate external public relay)',
        justification: isEarliestHop
          ? `First public IP encountered in chronological relay order (hop #${hop.hopIndex}). Note: If hops were prepended before submission, this could reflect attacker spoofing.`
          : `Intermediate public mail relay observed at hop #${hop.hopIndex} (by ${hop.byServer || 'unknown'}).`,
        ipType: 'public',
        attributionCategory: isEarliestHop ? 'candidate_originating' : 'observed_relay',
        trustBoundary: 'untrusted_external',
        isSpecialPurpose: false,
        hopIndex: hop.hopIndex,
        rawPositionFromTop: hop.rawPositionFromTop
      });
    } else {
      // Private, loopback, documentation, CGNAT, etc.
      candidates.push({
        ip: hop.ipAddress,
        confidence: `Low (Special-purpose ${ipDetails.category})`,
        justification: `Hop #${hop.hopIndex} contains special-purpose address ${hop.ipAddress} (${ipDetails.details}). Non-routable on the public internet; reflects internal network infrastructure or private submission.`,
        ipType: hop.ipType,
        attributionCategory: 'observed_relay',
        trustBoundary: 'internal_submission',
        isSpecialPurpose: true,
        hopIndex: hop.hopIndex,
        rawPositionFromTop: hop.rawPositionFromTop
      });
    }
  }

  return candidates;
}

/**
 * Analyzes identity headers for spoofing, mismatch, and display anomalies
 */
export function analyzeIdentityMismatches(
  envelope: EmailEnvelope, 
  rawHeaders: Record<string, string | string[]>
): EvidenceFinding[] {
  const findings: EvidenceFinding[] = [];
  const now = new Date().toISOString();

  const fromDomain = envelope.from?.domain?.toLowerCase();
  const returnPathDomain = envelope.returnPathDomain?.toLowerCase();
  const replyToDomain = envelope.replyTo?.domain?.toLowerCase();

  // 1. From vs Return-Path domain mismatch
  if (fromDomain && returnPathDomain && fromDomain !== returnPathDomain) {
    const isSubdomain = fromDomain.endsWith(`.${returnPathDomain}`) || returnPathDomain.endsWith(`.${fromDomain}`);
    if (!isSubdomain) {
      findings.push({
        findingId: 'ID-001',
        findingType: 'From_ReturnPath_Mismatch',
        value: `From: ${fromDomain} vs Return-Path: ${returnPathDomain}`,
        status: 'warning',
        source: 'RFC 5322 Envelope Headers',
        observedAt: now,
        explanation: `The visible 'From' domain (${fromDomain}) differs from the envelope 'Return-Path' domain (${returnPathDomain}). While legitimate mailing services use bounce return paths, attackers frequently abuse this to spoof brand domains.`,
        confidence: 0.85,
        supportingEvidenceReferences: ['From', 'Return-Path']
      });
    }
  }

  // 2. From vs Reply-To domain mismatch
  if (fromDomain && replyToDomain && fromDomain !== replyToDomain) {
    const isSubdomain = fromDomain.endsWith(`.${replyToDomain}`) || replyToDomain.endsWith(`.${fromDomain}`);
    if (!isSubdomain) {
      findings.push({
        findingId: 'ID-002',
        findingType: 'From_ReplyTo_Mismatch',
        value: `From: ${fromDomain} vs Reply-To: ${replyToDomain}`,
        status: 'warning',
        source: 'RFC 5322 Headers',
        observedAt: now,
        explanation: `The 'Reply-To' domain (${replyToDomain}) redirects replies away from the apparent sender domain (${fromDomain}). This is a frequent indicator of email redirection or credential harvesting.`,
        confidence: 0.9,
        supportingEvidenceReferences: ['From', 'Reply-To']
      });
    }
  }

  // 3. Display Name Spoofing
  if (envelope.from?.name) {
    const name = envelope.from.name.toLowerCase();
    const emailInNameMatch = name.match(/[\w.-]+@[\w.-]+\.[a-z]{2,}/i);
    if (emailInNameMatch) {
      const emailInName = emailInNameMatch[0].toLowerCase();
      if (envelope.from.address && emailInName !== envelope.from.address.toLowerCase()) {
        findings.push({
          findingId: 'ID-003',
          findingType: 'Display_Name_Email_Deception',
          value: `Display Name: "${envelope.from.name}" vs Address: ${envelope.from.address}`,
          status: 'fail',
          source: 'From Header Display Name',
          observedAt: now,
          explanation: `The sender display name embeds an email address (${emailInName}) that contradicts the actual sending mailbox (${envelope.from.address}). This is a classic visual deception tactic.`,
          confidence: 0.95,
          supportingEvidenceReferences: ['From']
        });
      }
    }

    // Check high-profile brand keywords in display name with unrelated domain
    const brandKeywords = ['paypal', 'microsoft', 'google', 'apple', 'amazon', 'bank of america', 'wells fargo', 'chase', 'netflix', 'dhl', 'fedex', 'usps'];
    for (const brand of brandKeywords) {
      if (name.includes(brand) && fromDomain && !fromDomain.includes(brand.replace(/\s+/g, ''))) {
        findings.push({
          findingId: `ID-004-${brand.replace(/\s+/g, '')}`,
          findingType: 'Brand_Display_Impersonation',
          value: `Display Name mentions '${brand}' but From domain is '${fromDomain}'`,
          status: 'fail',
          source: 'From Header',
          observedAt: now,
          explanation: `The sender display name claims identity with brand '${brand}', but the actual sender domain (${fromDomain}) has no demonstrable association with that brand.`,
          confidence: 0.9,
          supportingEvidenceReferences: ['From']
        });
        break;
      }
    }
  }

  return findings;
}

/**
 * Analyzes Message-ID header characteristics
 */
export function analyzeMessageId(
  messageId: string | undefined, 
  envelope: EmailEnvelope
): EvidenceFinding[] {
  const findings: EvidenceFinding[] = [];
  const now = new Date().toISOString();

  if (!messageId) {
    findings.push({
      findingId: 'MID-001',
      findingType: 'Missing_Message_ID',
      value: 'Missing',
      status: 'warning',
      source: 'Message-ID Header',
      observedAt: now,
      explanation: 'Message-ID header is missing. RFC 5322 strongly recommends a globally unique Message-ID; its absence is common in automated spam tools or ad-hoc scripts.',
      confidence: 0.8,
      supportingEvidenceReferences: ['Message-ID']
    });
    return findings;
  }

  const match = messageId.match(/<([^@]+)@([^>]+)>/);
  if (!match) {
    findings.push({
      findingId: 'MID-002',
      findingType: 'Malformed_Message_ID',
      value: messageId,
      status: 'warning',
      source: 'Message-ID Header',
      observedAt: now,
      explanation: 'Message-ID does not conform to standard RFC 5322 syntax (<id@domain>).',
      confidence: 0.7,
      supportingEvidenceReferences: ['Message-ID']
    });
  } else {
    const midDomain = match[2].toLowerCase();
    const fromDomain = envelope.from?.domain?.toLowerCase();

    if (fromDomain && midDomain !== fromDomain && !fromDomain.endsWith(`.${midDomain}`) && !midDomain.endsWith(`.${fromDomain}`)) {
      findings.push({
        findingId: 'MID-003',
        findingType: 'Message_ID_Domain_Mismatch',
        value: `Message-ID domain: ${midDomain} vs From domain: ${fromDomain}`,
        status: 'info',
        source: 'Message-ID Header',
        observedAt: now,
        explanation: `Message-ID domain (${midDomain}) differs from the sender domain (${fromDomain}). This can occur naturally when using hosted infrastructure (e.g. Amazon SES, SendGrid) or may signify external mail generation.`,
        confidence: 0.6,
        supportingEvidenceReferences: ['Message-ID', 'From']
      });
    }
  }

  return findings;
}

/**
 * Master header forensics pipeline
 */
export function runHeaderForensics(
  receivedHeaders: string[],
  envelope: EmailEnvelope,
  rawHeaders: Record<string, string | string[]>
): HeaderForensicResults {
  const receivedHops = parseReceivedChain(receivedHeaders);
  const candidateSourceIps = identifyCandidateSourceIps(receivedHops);
  const identityMismatches = analyzeIdentityMismatches(envelope, rawHeaders);
  const messageIdAnomalies = analyzeMessageId(envelope.messageId, envelope);

  const routingAnomalies: EvidenceFinding[] = [];
  const dateAnomalies: EvidenceFinding[] = [];
  const now = new Date().toISOString();

  // Aggregate hop-level suspicious signals
  for (const hop of receivedHops) {
    for (const signal of hop.suspiciousSignals) {
      routingAnomalies.push({
        findingId: `ROUT-${hop.hopIndex}`,
        findingType: 'Routing_Anomaly',
        value: `Hop #${hop.hopIndex} (from top: ${hop.rawPositionFromTop}): ${signal}`,
        status: 'warning',
        source: `Received Hop #${hop.hopIndex}`,
        observedAt: now,
        explanation: signal,
        confidence: 0.85,
        supportingEvidenceReferences: [`Received[${hop.rawPositionFromTop}]`]
      });
    }
  }

  // Date validity check
  if (envelope.date) {
    const parsedDate = new Date(envelope.date);
    if (isNaN(parsedDate.getTime())) {
      dateAnomalies.push({
        findingId: 'DATE-001',
        findingType: 'Invalid_Date_Header',
        value: envelope.date,
        status: 'warning',
        source: 'Date Header',
        observedAt: now,
        explanation: `Date header could not be parsed into a valid UTC timestamp: "${envelope.date}".`,
        confidence: 0.9,
        supportingEvidenceReferences: ['Date']
      });
    } else {
      const nowMs = Date.now();
      // Future date check (> 2 hours into future)
      if (parsedDate.getTime() > nowMs + 7200000) {
        dateAnomalies.push({
          findingId: 'DATE-002',
          findingType: 'Future_Timestamp',
          value: envelope.date,
          status: 'warning',
          source: 'Date Header',
          observedAt: now,
          explanation: `Date header is set in the future (${Math.round((parsedDate.getTime() - nowMs) / 3600000)}h ahead of current system time). This may indicate time tampering or incorrect mail server clock settings.`,
          confidence: 0.8,
          supportingEvidenceReferences: ['Date']
        });
      }
    }
  }

  return {
    receivedHops,
    candidateSourceIps,
    routingAnomalies,
    identityMismatches,
    messageIdAnomalies,
    dateAnomalies
  };
}
